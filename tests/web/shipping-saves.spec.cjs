const {test,expect}=require('@playwright/test');
const {button,tap,ready,menu,save,rows,exported,imported}=require('./save-helpers.cjs');
const release=process.env.MEU_RELEASE==='1';
test('persists a saved journey through normal controls with diagnostics absent',async({page,context,isMobile},info)=>{
  test.skip(!release,'Runs against optimized and live shipping clients.');
  const errors=[];const observe=p=>p.on('pageerror',e=>errors.push(String(e)));
  observe(page);context.on('page',observe);
  await ready(page);expect(await page.evaluate(()=>typeof window.MEU.readState)).toBe('undefined');
  await tap(button(page,'Settings'),isMobile);
  await tap(page.locator('label[for="invert-y"]'),isMobile);
  await tap(button(page,'Close settings'),isMobile);
  await menu(page,isMobile);await save(page,isMobile,1);
  const original=await rows(page),backup=await exported(page,isMobile);
  expect(backup.length).toBe(128);expect(backup.readUInt32LE(8)).toBe(1);expect(backup.readUInt32LE(92)&4).toBe(4);
  const next=await context.newPage();await page.close();page=next;await ready(page);
  expect(await page.evaluate(()=>typeof window.MEU.readState)).toBe('undefined');
  await expect(page.locator('#save-note')).toContainText('Loaded saved journey 1');
  await expect(page.locator('body')).toHaveAttribute('data-paused','true');
  await expect(button(page,'Resume exploration')).toBeEnabled();
  await tap(button(page,'Settings'),isMobile);await expect(page.locator('#invert-y')).toBeChecked();
  await tap(button(page,'Close settings'),isMobile);await menu(page,isMobile);
  await imported(page,isMobile,backup);
  await expect(page.locator('body')).toHaveAttribute('data-save-state','imported');
  expect((await rows(page)).latest).toBe(original.latest);
  await page.screenshot({path:info.outputPath('shipping-saved-journey.png')});
  await tap(button(page,'Close journeys'),isMobile);await tap(button(page,'Resume exploration'),isMobile);
  await expect(page.locator('body')).toHaveAttribute('data-paused','false');
  expect(errors).toEqual([]);
});
